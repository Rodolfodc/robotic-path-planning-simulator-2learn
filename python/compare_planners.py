"""
Compares Potential Fields (local/reactive planner) with A* (global planner)
on the SAME random scenario (identical start, goal and obstacles).

Reuses the existing scripts:
  - potential_fields.py : generate_obstacles(), plan()
  - astar.py            : a_star(), OBSTACLE

Usage: python compare_planners.py [seed] [--quiet]
  --quiet : silences the potential_fields force log

Can also be imported (see follow_path.py): create_scenario(), run_pf(),
run_astar(), path_length().
"""

import sys
import time

import numpy as np
import matplotlib.pyplot as plt

import potential_fields as pf
from astar import a_star, OBSTACLE

START = np.array([0.0, 0.0])
GOAL = np.array([10.0, 10.0])
N_OBSTACLES = 4

res = 0.2          # A* grid cell size
margin = 0.1       # safety margin around obstacles


# ---------------------------------------------------------------
# 1. Scenario (generated by potential_fields.py)
# ---------------------------------------------------------------
def create_scenario(seed=None):
    """Returns (seed, obstacles). Same seed -> same scenario."""
    if seed is None:
        seed = int(np.random.SeedSequence().entropy % 2**32)
    rng = np.random.default_rng(seed)
    return seed, pf.generate_obstacles(N_OBSTACLES, rng, START, GOAL)


# ---------------------------------------------------------------
# 2. Grid for A* (rasterizes the same circles)
#    grid[y, x]: weight 1 = free, OBSTACLE = blocked
# ---------------------------------------------------------------
def create_grid(obstacles):
    n = int(round(10 / res)) + 1
    xs = np.arange(n) * res
    X, Y = np.meshgrid(xs, xs)                   # X[y, x], Y[y, x]
    grid = np.ones((n, n))
    for center, radius in obstacles:
        grid[np.hypot(X - center[0], Y - center[1]) <= radius + margin] = OBSTACLE
    return grid


def path_length(path):
    path = np.asarray(path)
    return float(np.sum(np.linalg.norm(np.diff(path, axis=0), axis=1)))


# ---------------------------------------------------------------
# 3. Running the planners. Both return (path Nx2, reached)
# ---------------------------------------------------------------
def run_pf(obstacles):
    return pf.plan(START, GOAL, obstacles)


def run_astar(grid):
    start_cell = tuple(np.round(START / res).astype(int))
    goal_cell = tuple(np.round(GOAL / res).astype(int))
    path, _ = a_star(grid, start_cell, goal_cell)
    if path is None:
        return np.array([START]), False
    return np.array(path) * res, True


# ---------------------------------------------------------------
# 4. Main program: runs, prints metrics and plots
# ---------------------------------------------------------------
def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    seed, obstacles = create_scenario(int(args[0]) if args else None)
    print("seed:", seed)
    for k, (c, r) in enumerate(obstacles):
        print(f"obstacle {k}: center=({c[0]:.2f}, {c[1]:.2f}) radius={r:.2f}")

    grid = create_grid(obstacles)

    pf.verbose = "--quiet" not in sys.argv   # force log goes to the terminal (stdout)
    t0 = time.perf_counter()
    traj_pf, ok_pf = run_pf(obstacles)
    t_pf = time.perf_counter() - t0

    t0 = time.perf_counter()
    traj_as, ok_as = run_astar(grid)
    t_as = time.perf_counter() - t0

    print()
    print(f"{'':<20}{'Potential Fields':>18}{'A*':>12}")
    print(f"{'reached the goal':<20}{str(ok_pf):>18}{str(ok_as):>12}")
    print(f"{'length':<20}{path_length(traj_pf):>18.2f}{path_length(traj_as):>12.2f}")
    print(f"{'points':<20}{len(traj_pf):>18d}{len(traj_as):>12d}")
    print(f"{'time (ms)':<20}{t_pf * 1e3:>18.1f}{t_as * 1e3:>12.1f}")

    fig, axs = plt.subplots(1, 2, figsize=(12, 6), sharex=True, sharey=True)
    for ax, traj, ok, title, color in [
        (axs[0], traj_pf, ok_pf, "Potential Fields (local)", "tab:blue"),
        (axs[1], traj_as, ok_as, "A* (global)", "tab:orange"),
    ]:
        ax.imshow(grid == OBSTACLE, origin="lower",
                  extent=(-res / 2, 10 + res / 2, -res / 2, 10 + res / 2),
                  cmap="Greys", alpha=0.5)
        for center, radius in obstacles:
            ax.add_patch(plt.Circle(center, radius, fill=False, color="k", lw=0.8))
        ax.plot(traj[:, 0], traj[:, 1], ".-", color=color, markersize=2,
                label=f"path (L={path_length(traj):.2f})")
        ax.plot(*START, "go", markersize=10, label="start")
        ax.plot(*GOAL, "r*", markersize=15, label="goal")
        ax.set_aspect("equal")
        ax.set_xlim(-1, 11)
        ax.set_ylim(-1, 11)
        ax.set_title(title + ("" if ok else " — FAILED"))
        ax.legend(loc="upper left")
    fig.suptitle(f"seed = {seed}")
    plt.tight_layout()
    plt.savefig("compare_planners.png", dpi=120)
    plt.show()


if __name__ == "__main__":
    main()
